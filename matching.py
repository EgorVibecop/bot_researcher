# Категория по умолчанию для всего, что прошло ядро, но не попало ни в одну группу
GENERIC = ("⚪", "Исследования")

ALL_CATEGORY_IDS = list(CATEGORIES.keys()) + ["research"]


def category_label(cid):
    if cid == "research":
        return GENERIC
    return CATEGORIES[cid][:2]


# Мягкие стоп-слова: отсекают, только если стоят в основной части названия.
# В уточнении они называют предмет исследования, а не роль — «Менеджер по
# исследованиям (Brand & Sales Lift)» это ресёрч, а не продажи.
SOFT_STOP_PATTERNS = _c([
    r"продаж", r"\bsales\b", r"account\s+manager",
])

# Уточнение в скобках или после тире роль не называет.
_QUALIFIER = re.compile(r"\(.*?\)|\[.*?\]|[—–]\s.*$|\s-\s.*$", re.S)


def main_part(title):
    """Название без уточнений — та часть, что называет саму роль."""
    return _QUALIFIER.sub(" ", title or "").strip()


def classify(title):
    """Возвращает список категорий или None, если вакансия не подходит."""
    texts = variants(title)
    if not _hits(RESEARCH_CORE, texts):
        return None
    if _hits(STOP_PATTERNS, texts):
        return None
    if _hits(SOFT_STOP_PATTERNS, [main_part(t) for t in texts]):
        return None
    cats = [cid for cid, (_e, _l, pats) in CATEGORIES.items()
            if _hits(pats, texts)]
    return cats or ["research"]


def match(title, extra_include=(), extra_exclude=()):
    """
    Полная проверка с учётом личных ключевых слов пользователя.

    extra_include — подстроки, которые делают вакансию подходящей,
                    даже если исследовательского корня в названии нет.
    extra_exclude — подстроки, которые вакансию отбрасывают.

    Возвращает (подходит: bool, категории: list[str]).
    """
    t = (title or "").lower()

    for word in extra_exclude:
        if word and word.lower() in t:
            return False, []

    cats = classify(title)
    if cats is not None:
        return True, cats

    texts = variants(title)
    for word in extra_include:
        if word and word.lower() in t:
            if _hits(STOP_PATTERNS, texts):
                return False, []
            own = [cid for cid, (_e, _l, pats) in CATEGORIES.items()
                   if _hits(pats, texts)]
            return True, own or ["research"]

    return False, []


